/**
 * Портфолио «Бриллиант Ремонт».
 *
 * TODO_OWNER: фото объектов до/после ещё не получены (см. docs/CONTENT-INPUTS.md,
 * раздел 3, «Фото объектов до/после (минимум 6)»). Пока массив пуст, страница
 * /portfolio показывает честный блок «Портфолио собирается», а секция работ
 * на главной не рендерится вовсе. Сток-фото и выдуманные объекты запрещены:
 * клиент приходит смотреть НАШИ стены, а не картинки из интернета.
 *
 * Как наполнить: положить снимки в public/brands/remont/photos/<id>-{before,after}.jpg
 * (одинаковый кадр, один и тот же ракурс и свет) и добавить запись сюда.
 */

export type PortfolioItem = {
  /** Латиницей, используется в ключах и в именах файлов. */
  id: string;
  /** Короткое название объекта: «Двухкомнатная в новостройке». */
  title: string;
  /** Район или населённый пункт: «Степной», «п. Ростоши». */
  district: string;
  /** Площадь стен в работе, м². */
  area: number;
  /** Что делали — формулировки из состава услуг. */
  works: string[];
  /** Путь к фото «до» относительно /public. */
  beforeSrc: string;
  /** Путь к фото «после» относительно /public. */
  afterSrc: string;
  /** Сколько рабочих дней заняло, по факту. */
  durationDays: number;
  /** Что было особенного: задача, сложность, решение. Без рекламы. */
  comment: string;
};

/** Объекты показываем только с реальными фото от владельца. */
export const PORTFOLIO: PortfolioItem[] = [];

/** Секции портфолио рендерятся только когда есть что показать. */
export const HAS_PORTFOLIO: boolean = PORTFOLIO.length > 0;
