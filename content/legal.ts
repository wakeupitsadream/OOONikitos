/** Контакты для канала обращений: почты пока нет, остаётся телефон (TODO_OWNER). */
export function policyContacts(site: SiteId): Contacts {
  return CONTACTS[site];
}

function phoneSentence(site: SiteId): string {
  const phones = CONTACTS[site].phones;
  if (phones.length === 0) return '';
  const list = phones
    .map((phone) => (phone.label ? `${formatPhone(phone.value)} (${phone.label})` : formatPhone(phone.value)))
    .join(', ');
  return list;
}

