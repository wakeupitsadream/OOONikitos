const NBSP = ' ';

/** Короткие слова, после которых пробел делаем неразрывным. */
const SHORT_WORDS =
  'а|в|во|и|к|ко|на|не|ни|но|о|об|от|по|с|со|у|за|из|до|для|при|над|под|про|то|же|бы|ли|или|как|что|уже|мы|вы|он|их|его|её|их';

/** Единицы, которые нельзя отрывать от числа. */
const UNITS = '₽|руб\\.|м²|м2|м|см|мм|кг|г|л|%|шт\\.|сот\\.|соток|сотка|сотки|дней|день|дня|лет|год|года|часа|часов|час|мин\\.|мин';

/**
 * Русская типографика: кавычки-ёлочки, длинное тире, неразрывные пробелы
 * после коротких слов и перед единицами измерения.
 */
export function typograf(input: string): string {
  if (!input) return input;
  let out = input;

  // Кавычки-ёлочки: "текст" → «текст»
  out = out.replace(/"([^"]*)"/g, '«$1»');

  // Дефис между пробелами → длинное тире с неразрывным пробелом слева
  out = out.replace(/(\S)\s+[-–]\s+/g, `$1${NBSP}— `);

  // Неразрывный пробел после коротких слов (в начале строки или после пробела/скобки)
  const shortWordRe = new RegExp(`(^|[\\s(«])(${SHORT_WORDS})\\s+`, 'gi');
  out = out.replace(shortWordRe, `$1$2${NBSP}`);

  // Неразрывный пробел между числом и единицей измерения
  const unitRe = new RegExp(`(\\d)\\s+(${UNITS})(?![\\wА-Яа-яЁё])`, 'g');
  out = out.replace(unitRe, `$1${NBSP}$2`);

  // «No. 10» и «№ 10» не разрываем
  out = out.replace(/№\s+/g, `№${NBSP}`);

  return out;
}
